# Runtime: startup code, UART driver, number printing and reading
# ---------------------------------------------------------------------------
#
# Register use in generated code:
#   x0        the accumulator (never touched by runtime routines except INP)
#   x1..x9    scratch
#   x10, x11  saved return addresses inside runtime routines
#   x19       base address of the data area
#   x20       mini UART base, x21 GPIO base

def emit_delay(a):
    loop = a.uniq("__dly")
    a.mov_imm(2, 150)
    a.label(loop)
    a.sub_imm(2, 2, 1)
    a.cbnz(2, loop)


def emit_uart_init(a):
    # GPIO 14 and 15 to alternate function 5 (mini UART TX and RX)
    a.ldr_w(1, 21, 0x04)
    a.mov_imm(2, 0x3F000)
    a.bic_reg(1, 1, 2)
    a.mov_imm(2, 0x12000)
    a.orr_reg(1, 1, 2)
    a.str_w(1, 21, 0x04)
    # switch off the pull up and pull down resistors on those pins
    a.mov_imm(1, 0)
    a.str_w(1, 21, 0x94)
    emit_delay(a)
    a.mov_imm(1, (1 << 14) | (1 << 15))
    a.str_w(1, 21, 0x98)
    emit_delay(a)
    a.mov_imm(1, 0)
    a.str_w(1, 21, 0x98)
    # mini UART: 8 bit, 115200 baud, receiver and transmitter on
    a.mov_imm(1, 1)
    a.str_w(1, 20, 0x04)        # AUX_ENABLE
    a.mov_imm(1, 0)
    a.str_w(1, 20, 0x60)        # AUX_MU_CNTL off while configuring
    a.str_w(1, 20, 0x44)        # AUX_MU_IER no interrupts
    a.mov_imm(1, 3)
    a.str_w(1, 20, 0x4C)        # AUX_MU_LCR 8 bit mode
    a.mov_imm(1, 0)
    a.str_w(1, 20, 0x50)        # AUX_MU_MCR
    a.mov_imm(1, 0xC6)
    a.str_w(1, 20, 0x48)        # AUX_MU_IIR clear the FIFOs
    a.mov_imm(1, 270)
    a.str_w(1, 20, 0x68)        # AUX_MU_BAUD, 250 MHz core clock gives 115200
    a.mov_imm(1, 3)
    a.str_w(1, 20, 0x60)        # AUX_MU_CNTL enable TX and RX


def emit_startup(a):
    a.label("__start")
    a.raw(0xD53800A0, "mrs x0, mpidr_el1")      # which core am I
    a.raw(0x92400400, "and x0, x0, #3")
    a.cbnz(0, "__park")                         # only core 0 runs the program
    a.mov_imm(1, STACK_TOP)
    a.mov_sp_from(1)
    a.adr(19, "__data")
    a.mov_imm(20, AUX_BASE)
    a.mov_imm(21, GPIO_BASE)
    emit_uart_init(a)
    a.mov_xzr(0)
    a.b("main")
    a.label("__park")
    a.wfe()
    a.b("__park")


def emit_runtime(a):
    # __halt: stop here forever
    a.label("__halt")
    a.wfe()
    a.b("__halt")

    # __putc: send the character in x1 (clobbers x2). LF is sent as CR LF.
    a.label("__putc")
    a.cmp_imm(1, 10)
    a.bcond("ne", "__putc_raw")
    a.label("__putc_cr")
    a.ldr_w(2, 20, 0x54)
    a.tbz(2, 5, "__putc_cr")
    a.mov_imm(2, 13)
    a.str_w(2, 20, 0x40)
    a.label("__putc_raw")
    a.ldr_w(2, 20, 0x54)
    a.tbz(2, 5, "__putc_raw")
    a.str_w(1, 20, 0x40)
    a.ret()

    # __nl: send a newline
    a.label("__nl")
    a.mov_imm(1, 10)
    a.b("__putc")

    # __getc: wait for a character, returned in x1
    a.label("__getc")
    a.ldr_w(1, 20, 0x54)
    a.tbz(1, 0, "__getc")
    a.ldr_w(1, 20, 0x40)
    a.ret()

    # __puts: send x4 bytes starting at address x3
    a.label("__puts")
    a.mov(10, 30)
    a.label("__puts_loop")
    a.cbz(4, "__puts_done")
    a.ldrb_zero(1, 3)
    a.bl("__putc")
    a.add_imm(3, 3, 1)
    a.sub_imm(4, 4, 1)
    a.b("__puts_loop")
    a.label("__puts_done")
    a.mov(30, 10)
    a.ret()

    # __print_int: print x1 as a signed decimal number followed by a newline
    a.label("__print_int")
    a.mov(10, 30)
    a.mov(9, 1)
    a.tbz(9, 63, "__pi_pos")
    a.mov_imm(1, 45)
    a.bl("__putc")
    a.neg(9, 9)
    a.label("__pi_pos")
    a.sub_imm(31, 31, 32)
    a.add_imm(5, 31, 32)
    a.mov_imm(6, 10)
    a.label("__pi_loop")
    a.udiv(7, 9, 6)
    a.msub(8, 7, 6, 9)
    a.add_imm(8, 8, 48)
    a.sub_imm(5, 5, 1)
    a.strb_zero(8, 5)
    a.mov(9, 7)
    a.cbnz(9, "__pi_loop")
    a.add_imm(6, 31, 32)
    a.label("__pi_out")
    a.ldrb_zero(1, 5)
    a.bl("__putc")
    a.add_imm(5, 5, 1)
    a.cmp_reg(5, 6)
    a.bcond("lo", "__pi_out")
    a.add_imm(31, 31, 32)
    a.bl("__nl")
    a.mov(30, 10)
    a.ret()

    # __read_int: read a decimal number typed on the UART into x0
    a.label("__read_int")
    a.mov(10, 30)
    a.mov_xzr(0)
    a.mov_xzr(4)
    a.mov_imm(6, 10)
    a.label("__ri_loop")
    a.bl("__getc")
    a.cmp_imm(1, 13)
    a.bcond("eq", "__ri_done")
    a.cmp_imm(1, 10)
    a.bcond("eq", "__ri_done")
    a.cmp_imm(1, 45)
    a.bcond("ne", "__ri_digit")
    a.mov_imm(4, 1)
    a.bl("__putc")
    a.b("__ri_loop")
    a.label("__ri_digit")
    a.sub_imm(5, 1, 48)
    a.cmp_imm(5, 9)
    a.bcond("hi", "__ri_loop")
    a.bl("__putc")
    a.madd(0, 0, 6, 5)
    a.b("__ri_loop")
    a.label("__ri_done")
    a.cbz(4, "__ri_pos")
    a.neg(0, 0)
    a.label("__ri_pos")
    a.bl("__nl")
    a.mov(30, 10)
    a.ret()


