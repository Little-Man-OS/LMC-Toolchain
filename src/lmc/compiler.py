class LmcError(Exception):
    def __init__(self, msg, loc=None):
        super().__init__(msg)
        self.msg = msg
        self.loc = loc

    def __str__(self):
        return f"{self.loc}: error: {self.msg}" if self.loc else f"error: {self.msg}"


class Loc:
    def __init__(self, path, line, full=None):
        self.path = path
        self.line = line
        self.full = full or path

    def __str__(self):
        return f"{self.path}:{self.line}"


