class Sym:
    def __init__(self, kind, off, count):
        self.kind, self.off, self.count = kind, off, count


def layout_data(prog):
    data = bytearray()
    if prog.max_slot >= 0:
        data.extend(bytes((prog.max_slot + 1) * 8))
    syms = {}
    for d in prog.decls:
        align = DATA_ALIGN[d.kind]
        while len(data) % align:
            data.append(0)
        off = len(data)
        data.extend(d.init)
        for name in d.names:
            syms[name] = Sym(d.kind, off, d.count)
    while len(data) % 8:
        data.append(0)
    return bytes(data), syms


def generate(prog, require_main=True):
    if require_main and "main" not in prog.code_labels:
        err = LmcError("no entry point: the program needs a 'main:' label")
        if not prog.collect:
            raise err
        prog.errors.append(err)
    data, syms = layout_data(prog)
    a = Asm()
    emit_startup(a)

    def access(op, loc):
        kind, val = op
        if kind == "imm":
            return ("imm", val)
        if kind == "slot":
            return ("mem", "DAT", val * 8, 1)
        if val in syms:
            s = syms[val]
            if s.kind in ("FLO", "DUB"):
                raise LmcError(f"'{val}' is a {s.kind}; floating point values can be "
                               f"declared but not loaded yet", loc)
            return ("mem", s.kind, s.off, s.count)
        if val in prog.code_labels:
            raise LmcError(f"'{val}' is a code label, not a data location", loc)
        raise LmcError(f"undefined data label '{val}'", loc)

    def load_to(reg, op, loc):
        acc = access(op, loc)
        if acc[0] == "imm":
            a.mov_imm(reg, acc[1])
        else:
            a.load(reg, acc[1], acc[2])

    def emit_item(item):
        _, m, op, loc = item
        if m == "HLT":
            a.b("__halt")
        elif m in ("BRA", "BRZ", "BRP"):
            target = op[1]
            if target not in prog.code_labels:
                if target in prog.data_labels:
                    raise LmcError(f"'{target}' is data, you can only branch to code", loc)
                raise LmcError(f"undefined label '{target}'", loc)
            if m == "BRA":
                a.b(target, loc)
            elif m == "BRZ":
                a.cbz(0, target, loc)
            else:
                a.cmp_imm(0, 0)
                a.bcond("ge", target, loc)
        elif m == "LDA":
            load_to(0, op, loc)
        elif m == "STA":
            acc = access(op, loc)
            a.store(0, acc[1], acc[2])
        elif m in ("ADD", "SUB"):
            load_to(1, op, loc)
            (a.add_reg if m == "ADD" else a.sub_reg)(0, 0, 1)
        elif m == "INP":
            a.bl("__read_int")
        elif m == "OUT":
            if op is None:
                a.mov(1, 0)
            else:
                load_to(1, op, loc)
            a.bl("__print_int")
        elif m == "OTC":
            if op is not None:
                acc = access(op, loc)
            if op is not None and acc[0] == "mem" and acc[3] > 1:
                a.mov_imm(3, acc[2])
                a.add_reg(3, 19, 3)
                a.mov_imm(4, acc[3])
                a.bl("__puts")
            else:
                if op is None:
                    a.mov(1, 0)
                else:
                    load_to(1, op, loc)
                a.uxtb(1, 1)
                a.bl("__putc")

    for item in prog.ir:
        if item[0] == "label":
            a.label(item[1])
            continue
        try:
            emit_item(item)
        except LmcError as e:
            if not prog.collect:
                raise
            prog.errors.append(e)

    a.label("__end_of_program")
    emit_runtime(a)
    while len(a.items) % 4:
        a.nop()
    a.label("__data")
    if "main" not in a.labels:       # only when an error was already reported
        a.labels["main"] = 0
    code = a.assemble()
    return a, code, data


