def enc_movz(rd, imm, hw): return 0xD2800000 | (hw << 21) | (imm << 5) | rd
def enc_movk(rd, imm, hw): return 0xF2800000 | (hw << 21) | (imm << 5) | rd
def enc_movn(rd, imm, hw): return 0x92800000 | (hw << 21) | (imm << 5) | rd
def enc_mov_reg(rd, rm): return 0xAA0003E0 | (rm << 16) | rd
def enc_add_reg(rd, rn, rm): return 0x8B000000 | (rm << 16) | (rn << 5) | rd
def enc_sub_reg(rd, rn, rm): return 0xCB000000 | (rm << 16) | (rn << 5) | rd
def enc_add_imm(rd, rn, imm): return 0x91000000 | (imm << 10) | (rn << 5) | rd
def enc_sub_imm(rd, rn, imm): return 0xD1000000 | (imm << 10) | (rn << 5) | rd
def enc_cmp_imm(rn, imm): return 0xF100001F | (imm << 10) | (rn << 5)
def enc_cmp_reg(rn, rm): return 0xEB00001F | (rm << 16) | (rn << 5)
def enc_neg(rd, rm): return 0xCB0003E0 | (rm << 16) | rd
def enc_orr_reg(rd, rn, rm): return 0xAA000000 | (rm << 16) | (rn << 5) | rd
def enc_bic_reg(rd, rn, rm): return 0x8A200000 | (rm << 16) | (rn << 5) | rd
def enc_udiv(rd, rn, rm): return 0x9AC00800 | (rm << 16) | (rn << 5) | rd
def enc_msub(rd, rn, rm, ra): return 0x9B008000 | (rm << 16) | (ra << 10) | (rn << 5) | rd
def enc_madd(rd, rn, rm, ra): return 0x9B000000 | (rm << 16) | (ra << 10) | (rn << 5) | rd
def enc_uxtb(rd, rn): return 0x53001C00 | (rn << 5) | rd
def enc_ldst(base, rt, rn, imm): return base | (imm << 10) | (rn << 5) | rt


COND = {"eq": 0, "ne": 1, "hs": 2, "lo": 3, "mi": 4, "pl": 5,
        "hi": 8, "ls": 9, "ge": 10, "lt": 11, "gt": 12, "le": 13}

# (opcode base, log2 size, mnemonic, register prefix)
LOAD_FORMS = {"DAT": (0xF9400000, 3, "ldr", "x"),
              "INT": (0xB9800000, 2, "ldrsw", "x"),
              "CHA": (0x39400000, 0, "ldrb", "w")}
STORE_FORMS = {"DAT": (0xF9000000, 3, "str", "x"),
               "INT": (0xB9000000, 2, "str", "w"),
               "CHA": (0x39000000, 0, "strb", "w")}


class Asm:
    """Collects instructions, resolves labels, and can print them as text."""

    def __init__(self):
        self.items = []      # (word or fixup function, text)
        self.labels = {}     # name -> instruction index
        self.words = []
        self.counter = 0

    def uniq(self, prefix):
        self.counter += 1
        return f"{prefix}{self.counter}"

    def label(self, name):
        self.labels[name] = len(self.items)

    def raw(self, word, text):
        self.items.append((word, text))

    def fixup(self, fn, text):
        self.items.append((fn, text))

    # --- register and immediate moves -------------------------------------
    def mov(self, rd, rm):
        self.raw(enc_mov_reg(rd, rm), f"mov x{rd}, x{rm}")

    def mov_xzr(self, rd):
        self.raw(enc_mov_reg(rd, 31), f"mov x{rd}, xzr")

    def mov_sp_from(self, rm):
        self.raw(enc_add_imm(31, rm, 0), f"mov sp, x{rm}")

    def mov_imm(self, rd, value):
        if not -(1 << 63) <= value <= MASK64:
            raise LmcError(f"value {value} does not fit in 64 bits")
        u = value & MASK64
        chunks = [(u >> (16 * i)) & 0xFFFF for i in range(4)]

        def fmt(op, imm, hw):
            s = f"{op} x{rd}, #{imm:#x}"
            return s + (f", lsl #{16 * hw}" if hw else "")

        if chunks.count(0xFFFF) > chunks.count(0):
            idx = [i for i, c in enumerate(chunks) if c != 0xFFFF] or [0]
            first = idx[0]
            imm = ~chunks[first] & 0xFFFF
            self.raw(enc_movn(rd, imm, first), fmt("movn", imm, first))
            for i in idx[1:]:
                self.raw(enc_movk(rd, chunks[i], i), fmt("movk", chunks[i], i))
        else:
            idx = [i for i, c in enumerate(chunks) if c != 0] or [0]
            first = idx[0]
            self.raw(enc_movz(rd, chunks[first], first), fmt("movz", chunks[first], first))
            for i in idx[1:]:
                self.raw(enc_movk(rd, chunks[i], i), fmt("movk", chunks[i], i))

    # --- arithmetic ---------------------------------------------------------
    def add_reg(self, rd, rn, rm):
        self.raw(enc_add_reg(rd, rn, rm), f"add x{rd}, x{rn}, x{rm}")

    def sub_reg(self, rd, rn, rm):
        self.raw(enc_sub_reg(rd, rn, rm), f"sub x{rd}, x{rn}, x{rm}")

    def add_imm(self, rd, rn, imm):
        d = "sp" if rd == 31 else f"x{rd}"
        n = "sp" if rn == 31 else f"x{rn}"
        self.raw(enc_add_imm(rd, rn, imm), f"add {d}, {n}, #{imm}")

    def sub_imm(self, rd, rn, imm):
        d = "sp" if rd == 31 else f"x{rd}"
        n = "sp" if rn == 31 else f"x{rn}"
        self.raw(enc_sub_imm(rd, rn, imm), f"sub {d}, {n}, #{imm}")

    def cmp_imm(self, rn, imm):
        self.raw(enc_cmp_imm(rn, imm), f"cmp x{rn}, #{imm}")

    def cmp_reg(self, rn, rm):
        self.raw(enc_cmp_reg(rn, rm), f"cmp x{rn}, x{rm}")

    def neg(self, rd, rm):
        self.raw(enc_neg(rd, rm), f"neg x{rd}, x{rm}")

    def orr_reg(self, rd, rn, rm):
        self.raw(enc_orr_reg(rd, rn, rm), f"orr x{rd}, x{rn}, x{rm}")

    def bic_reg(self, rd, rn, rm):
        self.raw(enc_bic_reg(rd, rn, rm), f"bic x{rd}, x{rn}, x{rm}")

    def udiv(self, rd, rn, rm):
        self.raw(enc_udiv(rd, rn, rm), f"udiv x{rd}, x{rn}, x{rm}")

    def msub(self, rd, rn, rm, ra):
        self.raw(enc_msub(rd, rn, rm, ra), f"msub x{rd}, x{rn}, x{rm}, x{ra}")

    def madd(self, rd, rn, rm, ra):
        self.raw(enc_madd(rd, rn, rm, ra), f"madd x{rd}, x{rn}, x{rm}, x{ra}")

    def uxtb(self, rd, rn):
        self.raw(enc_uxtb(rd, rn), f"uxtb w{rd}, w{rn}")

    # --- memory ---------------------------------------------------------------
    def data_access(self, forms, rt, kind, off):
        """Load or store through the data base register (x19)."""
        base, shift, mn, rp = forms[kind]
        scaled = off >> shift
        if off % (1 << shift) == 0 and scaled < 4096:
            addr = f"[x19, #{off}]" if off else "[x19]"
            self.raw(enc_ldst(base, rt, 19, scaled), f"{mn} {rp}{rt}, {addr}")
        else:
            self.mov_imm(2, off)
            self.add_reg(2, 19, 2)
            self.raw(enc_ldst(base, rt, 2, 0), f"{mn} {rp}{rt}, [x2]")

    def load(self, rt, kind, off):
        self.data_access(LOAD_FORMS, rt, kind, off)

    def store(self, rt, kind, off):
        self.data_access(STORE_FORMS, rt, kind, off)

    def ldr_w(self, rt, rn, off):
        self.raw(enc_ldst(0xB9400000, rt, rn, off >> 2), f"ldr w{rt}, [x{rn}, #{off}]")

    def str_w(self, rt, rn, off):
        self.raw(enc_ldst(0xB9000000, rt, rn, off >> 2), f"str w{rt}, [x{rn}, #{off}]")

    def ldrb_zero(self, rt, rn):
        self.raw(enc_ldst(0x39400000, rt, rn, 0), f"ldrb w{rt}, [x{rn}]")

    def strb_zero(self, rt, rn):
        self.raw(enc_ldst(0x39000000, rt, rn, 0), f"strb w{rt}, [x{rn}]")

    # --- branches ----------------------------------------------------------------
    def _offset(self, name, idx, labels, bits, loc):
        if name not in labels:
            raise LmcError(f"undefined label '{name}'", loc)
        off = labels[name] - idx
        lim = 1 << (bits - 1)
        if not -lim <= off < lim:
            raise LmcError(f"branch to '{name}' is too far away", loc)
        return off & ((1 << bits) - 1)

    def b(self, name, loc=None):
        self.fixup(lambda i, L: 0x14000000 | self._offset(name, i, L, 26, loc), f"b {name}")

    def bl(self, name, loc=None):
        self.fixup(lambda i, L: 0x94000000 | self._offset(name, i, L, 26, loc), f"bl {name}")

    def bcond(self, cond, name, loc=None):
        c = COND[cond]
        self.fixup(lambda i, L: 0x54000000 | (self._offset(name, i, L, 19, loc) << 5) | c,
                   f"b.{cond} {name}")

    def cbz(self, rt, name, loc=None):
        self.fixup(lambda i, L: 0xB4000000 | (self._offset(name, i, L, 19, loc) << 5) | rt,
                   f"cbz x{rt}, {name}")

    def cbnz(self, rt, name, loc=None):
        self.fixup(lambda i, L: 0xB5000000 | (self._offset(name, i, L, 19, loc) << 5) | rt,
                   f"cbnz x{rt}, {name}")

    def tbz(self, rt, bit, name, loc=None):
        self._tb(0x36000000, "tbz", rt, bit, name, loc)

    def tbnz(self, rt, bit, name, loc=None):
        self._tb(0x37000000, "tbnz", rt, bit, name, loc)

    def _tb(self, base, mn, rt, bit, name, loc):
        b5, b40 = bit >> 5, bit & 31
        reg = ("x" if bit >= 32 else "w") + str(rt)
        self.fixup(lambda i, L: base | (b5 << 31) | (b40 << 19)
                   | (self._offset(name, i, L, 14, loc) << 5) | rt,
                   f"{mn} {reg}, #{bit}, {name}")

    def adr(self, rd, name, loc=None):
        def enc(i, L):
            if name not in L:
                raise LmcError(f"undefined label '{name}'", loc)
            off = (L[name] - i) * 4
            if not -(1 << 20) <= off < (1 << 20):
                raise LmcError("program is too large (code must stay under 1 MiB)", loc)
            off &= (1 << 21) - 1
            return 0x10000000 | ((off & 3) << 29) | ((off >> 2) << 5) | rd
        self.fixup(enc, f"adr x{rd}, {name}")

    def ret(self): self.raw(0xD65F03C0, "ret")
    def wfe(self): self.raw(0xD503205F, "wfe")
    def nop(self): self.raw(0xD503201F, "nop")

    # --- output ------------------------------------------------------------------
    def assemble(self):
        self.words = []
        for idx, (w, _text) in enumerate(self.items):
            self.words.append(w(idx, self.labels) if callable(w) else w)
        return b"".join(struct.pack("<I", w) for w in self.words)

    def label_names_at(self):
        at = {}
        for name, idx in self.labels.items():
            at.setdefault(idx, []).append(name)
        return at


