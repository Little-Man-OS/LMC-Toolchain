#!/usr/bin/env python3
"""
lmcc: a compiler for LMC (Little Man Computer) that targets bare metal
Raspberry Pi 3B (AArch64, no operating system).

It turns .lmc source into a flat binary called kernel8.img, which the Pi
firmware loads at 0x80000 and runs directly. No assembler or linker is
needed, the machine code is generated by this file. It can also write the
same program out as GNU assembly (-S) or as a readable listing (-l).

Usage:
    lmcc prog.lmc                 builds kernel8.img
    lmcc prog.lmc -o out.img      choose the output file
    lmcc prog.lmc -S prog.s       also write GNU assembly
    lmcc prog.lmc -l              print a listing
    lmcc prog.lmc --run           build, then run in QEMU
    lmcc --examples               copy the example programs to ./lmc-examples

IMP files are looked for next to the file that imports them, then in any -I folders.

See README.md for the language reference.
"""
