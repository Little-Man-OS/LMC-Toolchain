LOAD_ADDR = 0x80000          # where the Pi firmware loads kernel8.img
STACK_TOP = 0x80000          # stack grows down from here, below the image
AUX_BASE = 0x3F215000        # mini UART block
GPIO_BASE = 0x3F200000
MASK64 = (1 << 64) - 1
MAX_SLOT = 0xFFFF

MNEMONICS = {"HLT", "ADD", "SUB", "STA", "LDA", "BRA", "BRZ", "BRP",
             "INP", "OUT", "OTC", "IMP"}
DATA_KW = {"DAT", "INT", "CHA", "FLO", "DUB"}
