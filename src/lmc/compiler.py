TOKEN = re.compile(r'#?"(?:\\.|[^"\\])*"|#?\'(?:\\.|[^\'\\])*\'|\S+')


def strip_comment(line):
    out, quote, i = [], None, 0
    while i < len(line):
        c = line[i]
        if quote:
            out.append(c)
            if c == "\\" and i + 1 < len(line):
                out.append(line[i + 1])
                i += 2
                continue
            if c == quote:
                quote = None
        elif c in "\"'":
            quote = c
            out.append(c)
        elif c == ";" or line[i:i + 2] == "//":
            break
        else:
            out.append(c)
        i += 1
    return "".join(out)


ESCAPES = {"n": "\n", "r": "\r", "t": "\t", "0": "\0", "\\": "\\", '"': '"', "'": "'"}


def unescape(body, loc):
    out, i = bytearray(), 0
    while i < len(body):
        c = body[i]
        if c == "\\":
            i += 1
            if i >= len(body):
                raise LmcError("bad escape at end of string", loc)
            e = body[i]
            if e == "x":
                hexdigits = body[i + 1:i + 3]
                if len(hexdigits) != 2 or not re.fullmatch(r"[0-9a-fA-F]{2}", hexdigits):
                    raise LmcError("bad \\x escape, expected two hex digits", loc)
                out.append(int(hexdigits, 16))
                i += 3
                continue
            if e not in ESCAPES:
                raise LmcError(f"unknown escape '\\{e}'", loc)
            out += ESCAPES[e].encode()
        else:
            out += c.encode("utf-8")
        i += 1
    return bytes(out)


def parse_int(tok, loc):
    tok = tok.strip()
    if len(tok) >= 3 and tok[0] == "'" and tok[-1] == "'":
        b = unescape(tok[1:-1], loc)
        if len(b) != 1:
            raise LmcError(f"character literal {tok} must be a single byte", loc)
        return b[0]
    try:
        v = int(tok, 0)
    except ValueError:
        raise LmcError(f"expected a number but found '{tok}'", loc)
    if not -(1 << 63) <= v <= MASK64:
        raise LmcError(f"number {tok} does not fit in 64 bits", loc)
    return v


def parse_operand(tok, loc):
    if tok.startswith("#"):
        return ("imm", parse_int(tok[1:], loc))
    if re.fullmatch(r"\d+|0[xX][0-9a-fA-F]+", tok):
        n = int(tok, 0)
        if n > MAX_SLOT:
            raise LmcError(f"slot number {n} is too large (maximum {MAX_SLOT})", loc)
        return ("slot", n)
    if IDENT.fullmatch(tok):
        return ("sym", tok)
    raise LmcError(f"bad operand '{tok}'", loc)


