def make_listing(a, code, data):
    at = a.label_names_at()
    lines = []
    for i, (_, text) in enumerate(a.items):
        for name in at.get(i, []):
            lines.append(f"{name}:")
        lines.append(f"  {LOAD_ADDR + 4 * i:08x}  {a.words[i]:08x}  {text}")
    for name in at.get(len(a.items), []):
        lines.append(f"{name}:")
    base = LOAD_ADDR + len(code)
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16].hex(" ")
        lines.append(f"  {base + i:08x}  {chunk}")
    return "\n".join(lines) + "\n"


def make_asm_source(a, data):
    at = a.label_names_at()
    out = ["// generated by lmcc, assemble with: aarch64-linux-gnu-as",
           "        .text", "        .globl _start", "_start:"]
    for i, (_, text) in enumerate(a.items):
        for name in at.get(i, []):
            out.append(f"{name}:")
        out.append(f"        {text}")
    out.append("        .balign 16")
    for name in at.get(len(a.items), []):
        out.append(f"{name}:")
    for i in range(0, len(data), 16):
        out.append("        .byte " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]))
    return "\n".join(out) + "\n"


def check(path, overrides=None, require_main=True, include_dirs=()):
    """Check a program without writing anything.

    overrides maps absolute file paths to unsaved source text, so an editor can check
    what is on screen. Returns (errors, set of files that were read).
    """
    prog = Program()
    prog.collect = True
    prog.include_dirs = list(include_dirs)
    prog.overrides = {os.path.abspath(k): v for k, v in (overrides or {}).items()}
    try:
        parse_file(path, prog)
    except LmcError as e:
        prog.errors.append(e)
    try:
        generate(prog, require_main)
    except LmcError as e:
        prog.errors.append(e)
    seen, unique = set(), []
    for e in prog.errors:
        key = (getattr(e.loc, "full", None), getattr(e.loc, "line", None), e.msg)
        if key not in seen:
            seen.add(key)
            unique.append(e)
    return sort_errors(unique), prog.imported


def compile_file(path, overrides=None, include_dirs=()):
    """Compile to (asm, code, data). Raises a CompileFailed holding every error."""
    prog = Program()
    prog.collect = True
    prog.include_dirs = list(include_dirs)
    prog.overrides = {os.path.abspath(k): v for k, v in (overrides or {}).items()}
    try:
        parse_file(path, prog)
    except LmcError as e:
        prog.errors.append(e)
    result = None
    try:
        result = generate(prog)
    except LmcError as e:
        prog.errors.append(e)
    if prog.errors:
        raise CompileFailed(prog.errors)
    return result


def sort_errors(errors):
    return sorted(errors, key=lambda e: (e.loc is None, getattr(e.loc, "full", ""),
                                         getattr(e.loc, "line", 0)))


class CompileFailed(Exception):
    def __init__(self, errors):
        super().__init__(f"{len(errors)} error(s)")
        self.errors = sort_errors(errors)


def main(argv=None):
    ap = argparse.ArgumentParser(description="LMC compiler for the Raspberry Pi 3B (bare metal AArch64)")
    ap.add_argument("source", nargs="?", help="the .lmc file with a 'main:' label")
    ap.add_argument("--examples", action="store_true", help="copy the example programs to ./lmc-examples")
    ap.add_argument("--version", action="version", version=f"lmcc {__version__}")
    ap.add_argument("-o", "--output", default="kernel8.img", help="output image (default kernel8.img)")
    ap.add_argument("-S", dest="asm_out", metavar="FILE", help="also write GNU assembly source")
    ap.add_argument("-I", dest="include_dirs", action="append", default=[], metavar="DIR",
                    help="also search DIR for IMP files (can be repeated)")
    ap.add_argument("-l", "--listing", action="store_true", help="print addresses, machine code and assembly")
    ap.add_argument("--run", action="store_true", help="run the image in QEMU after building")
    args = ap.parse_args(argv)

    if args.examples:
        here = os.path.join(os.path.dirname(os.path.abspath(__file__)), "examples")
        dest = "lmc-examples"
        os.makedirs(dest, exist_ok=True)
        for name in sorted(os.listdir(here)):
            if name.endswith(".lmc"):
                shutil.copy(os.path.join(here, name), dest)
                print(f"{os.path.join(dest, name)}")
        return 0
    if not args.source:
        ap.error("give the .lmc file to compile, or use --examples")

    try:
        a, code, data = compile_file(args.source, include_dirs=args.include_dirs)
    except CompileFailed as failure:
        for e in failure.errors:
            print(e, file=sys.stderr)
        n = len(failure.errors)
        print(f"{n} error{'s' if n != 1 else ''}, nothing was built", file=sys.stderr)
        return 1

    image = code + data
    with open(args.output, "wb") as fh:
        fh.write(image)
    if args.asm_out:
        with open(args.asm_out, "w") as fh:
            fh.write(make_asm_source(a, data))
    if args.listing:
        sys.stdout.write(make_listing(a, code, data))
    print(f"{args.output}: {len(image)} bytes (code {len(code)}, data {len(data)}), loads at {LOAD_ADDR:#x}",
          file=sys.stderr)

    if args.run:
        qemu = shutil.which("qemu-system-aarch64")
        if not qemu:
            print("qemu-system-aarch64 was not found on your PATH", file=sys.stderr)
            return 1
        print("running in QEMU, press Ctrl-A then X to quit", file=sys.stderr)
        return subprocess.call([qemu, "-M", "raspi3b", "-kernel", args.output, "-display", "none",
                                "-serial", "null", "-serial", "mon:stdio"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
